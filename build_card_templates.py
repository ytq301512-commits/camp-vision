def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for source, names, boxes in SETS:
        image = cv2.imread(str(source))
        if image is None:
            raise FileNotFoundError(source)
        if len(names) != len(boxes):
            raise ValueError(f"template count mismatch for {source}")
        for name, (x, y, w, h) in zip(names, boxes):
            crop = image[y : y + h, x : x + w]
            if crop.size == 0:
                raise ValueError(f"empty crop for {name}")
            ok, encoded = cv2.imencode(".png", crop)
            if not ok:
                raise RuntimeError(f"cannot encode template for {name}")
            (OUT / f"{name}.png").write_bytes(encoded.tobytes())
    print(f"Wrote {len(list(OUT.glob('*.png')))} templates to {OUT}")


if __name__ == "__main__":
    main()
